"""Extract the client's vector logos from the trademark PDF.
Usage: python -I logos.py <trademark.pdf> <project_root>
Writes src/components/brand/marks.ts (path data) and public/brand/*.svg.
"""
import sys, os, json
import pymupdf

pdf, proj = sys.argv[1], sys.argv[2]
doc = pymupdf.open(pdf)


def hexc(c):
    return "#%02x%02x%02x" % tuple(round(x * 255) for x in c)


def path_d(g, ox, oy):
    d, cur = [], None

    def pt(p):
        return "%.2f %.2f" % (p.x - ox, p.y - oy)

    for it in g["items"]:
        k = it[0]
        if k == "l":
            a, b = it[1], it[2]
            if cur is None or abs(a.x - cur.x) > 0.01 or abs(a.y - cur.y) > 0.01:
                d.append("M" + pt(a))
            d.append("L" + pt(b))
            cur = b
        elif k == "c":
            a, b, c, e = it[1], it[2], it[3], it[4]
            if cur is None or abs(a.x - cur.x) > 0.01 or abs(a.y - cur.y) > 0.01:
                d.append("M" + pt(a))
            d.append("C%s %s %s" % (pt(b), pt(c), pt(e)))
            cur = e
        elif k == "re":
            r = it[1]
            d.append("M%.2f %.2f H%.2f V%.2f H%.2f Z" % (r.x0 - ox, r.y0 - oy, r.x1 - ox, r.y1 - oy, r.x0 - ox))
            cur = None
        elif k == "qu":
            q = it[1]
            d.append("M%s L%s L%s L%s Z" % (pt(q.ul), pt(q.ur), pt(q.lr), pt(q.ll)))
            cur = None
    if g.get("closePath"):
        d.append("Z")
    return "".join(d)


def shapes(page_no):
    page = doc[page_no - 1]
    out = []
    for g in page.get_drawings():
        r = g["rect"]
        if r.width > page.rect.width * 0.9 and r.height > page.rect.height * 0.9:
            continue  # page background
        if not g.get("fill"):
            continue
        out.append(g)
    return out


def build(gs):
    x0 = min(g["rect"].x0 for g in gs); y0 = min(g["rect"].y0 for g in gs)
    x1 = max(g["rect"].x1 for g in gs); y1 = max(g["rect"].y1 for g in gs)
    paths = []
    for g in gs:
        paths.append({"d": path_d(g, x0, y0), "fill": hexc(g["fill"]), "evenodd": bool(g.get("even_odd"))})
    return {"w": round(x1 - x0, 2), "h": round(y1 - y0, 2), "paths": paths}


marks = {}
# Sagework wordmark without tagline (page 2). The leaf is the right-most shape.
gs = shapes(2)
gs.sort(key=lambda g: g["rect"].x0)
marks["sagework"] = build(gs)
leaf = [gs[-1]]
marks["leaf"] = build(leaf)
marks["sageworkWord"] = build(gs[:-1])
print("sagework shapes", len(gs), "leaf rect", leaf[0]["rect"], "prev rect", gs[-2]["rect"])

marks["simplySage"] = build(shapes(13))
marks["simplySageBy"] = build(shapes(16))
marks["drGutsy"] = build(shapes(17))
marks["drGutsyTag"] = build(shapes(21))
marks["triadA"] = build(shapes(9))
marks["triadB"] = build(shapes(10))
for k, v in marks.items():
    print(k, v["w"], v["h"], len(v["paths"]), sorted(set(p["fill"] for p in v["paths"])))

os.makedirs(os.path.join(proj, "public", "brand"), exist_ok=True)


def svg(m, mono=None, pad=0):
    body = "".join('<path d="%s" fill="%s"%s/>' % (p["d"], mono or p["fill"], ' fill-rule="evenodd"' if p["evenodd"] else "") for p in m["paths"])
    return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="%s %s %s %s">%s</svg>' % (-pad, -pad, m["w"] + 2 * pad, m["h"] + 2 * pad, body)


for k in marks:
    open(os.path.join(proj, "public", "brand", k + ".svg"), "w", encoding="utf-8").write(svg(marks[k]))

ts = ["// Generated by scripts/extract-logos.py from the client's trademark PDF. Do not edit by hand.",
      "// The artwork is the client's registered identity: never redraw, recolour beyond the approved",
      "// green / white / black, outline, distort or add effects (brand manual, page 16).",
      "export type Mark = { w: number; h: number; paths: { d: string; fill: string; evenodd: boolean }[] };",
      "export const marks = " + json.dumps(marks, separators=(",", ":")) + " as const satisfies Record<string, Mark>;",
      "export type MarkName = keyof typeof marks;", ""]
os.makedirs(os.path.join(proj, "src", "components", "brand"), exist_ok=True)
open(os.path.join(proj, "src", "components", "brand", "marks.ts"), "w", encoding="utf-8", newline="\n").write("\n".join(ts))
print("written")
